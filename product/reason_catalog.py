CATALOG: dict[str, ReasonExplanation] = dict(_ENTRIES)


def lookup(reason_code: str) -> ReasonExplanation | None:
    """精确查找（未收录 ⇒ None，绝不返回近似的猜测）。"""
    if not isinstance(reason_code, str):
        raise TypeError("lookup() requires a reason code string")
    return CATALOG.get(reason_code)


def explain_reason(reason_code: object) -> ReasonExplanation:
    """总是返回一个解释：已收录 ⇒ 目录文案；未收录 ⇒ 原始 code + 暂无解释。"""
    code = str(reason_code)
    found = CATALOG.get(code)
    if found is not None:
        return found
    return ReasonExplanation(reason_code=code, title=UNKNOWN_TITLE, explanation=UNKNOWN_EXPLANATION,
                             severity="UNKNOWN", suggested_next_step=UNKNOWN_NEXT_STEP,
                             domain="unknown", title_en="no explanation available",
                             explanation_en=UNKNOWN_EXPLANATION_EN,
                             suggested_next_step_en=UNKNOWN_NEXT_STEP_EN, catalogued=False)


def catalog_payload() -> tuple[dict[str, object], ...]:
    """按 code 排序的稳定目录载荷（API / UI / CLI / Assistant 共用）。"""
    return tuple(CATALOG[code].to_payload() for code in sorted(CATALOG))


def explain_codes(codes: object) -> dict[str, dict[str, object]]:
    """为一批 code 生成解释映射（去重、按 code 排序；未知 code 保留原始 key）。"""
    unique = sorted({str(code) for code in (codes or ()) if str(code)})
    return {code: explain_reason(code).to_payload() for code in unique}


