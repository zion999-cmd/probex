#: 未收录 code 的固定文案（绝不猜测业务语义）
UNKNOWN_TITLE = "暂无解释"
UNKNOWN_EXPLANATION = "catalog 未收录该 reason code；保留原始 code，未推断语义。"
UNKNOWN_EXPLANATION_EN = ("this reason code is not in the catalog; the raw code is preserved "
                          "and its semantics are not guessed")
UNKNOWN_NEXT_STEP = "查阅产生该 code 的 Owner（见 blocker.source_ref / 原始事实）。"
UNKNOWN_NEXT_STEP_EN = "open the owning component that emitted the code (see source_ref / raw facts)"


@dataclass(frozen=True, slots=True)
class ReasonExplanation:
    """一个 reason code 的人类可读解释（presentation-only）。"""

    reason_code: str
    title: str
    explanation: str
    severity: str
    suggested_next_step: str
    domain: str
    title_en: str = ""
    explanation_en: str = ""
    suggested_next_step_en: str = ""
    catalogued: bool = True

    def __post_init__(self) -> None:
        if not isinstance(self.reason_code, str) or not self.reason_code:
            raise ValueError("ReasonExplanation.reason_code must be a non-empty string")
        for name in ("title", "explanation", "severity", "suggested_next_step", "domain"):
            value = getattr(self, name)
            if not isinstance(value, str) or not value:
                raise ValueError(f"ReasonExplanation.{name} must be a non-empty string")

    def to_payload(self) -> dict[str, object]:
        return {
            "reason_code": self.reason_code,
            "title": self.title,
            "explanation": self.explanation,
            "severity": self.severity,
            "suggested_next_step": self.suggested_next_step,
            "domain": self.domain,
            "title_en": self.title_en or self.title,
            "explanation_en": self.explanation_en or self.explanation,
            "suggested_next_step_en": self.suggested_next_step_en or self.suggested_next_step,
            "catalogued": self.catalogued,
        }


def _entry(code: str, *, title: str, explanation: str, severity: str, next_step: str, domain: str,
           title_en: str = "", explanation_en: str = "", next_step_en: str = "") -> tuple[str, ReasonExplanation]:
    return code, ReasonExplanation(reason_code=code, title=title, explanation=explanation,
                                   severity=severity, suggested_next_step=next_step, domain=domain,
                                   title_en=title_en, explanation_en=explanation_en,
                                   suggested_next_step_en=next_step_en)


