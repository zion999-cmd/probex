"""F-09 Reason Code 人类解释层（**纯 presentation catalog**）。

边界（人类裁决 / Slice 4 §2）：

- 原始 `reason_code` **永远保留**（本模块只做附加解释，绝不替换 / 改写 code）；
- catalog **不参与任何决策**（RiskGate / Readiness / Execution authority / Governor 都不 import 本模块）；
- 未收录的 code ⇒ 返回 `raw code + 暂无解释`，**不猜语义**；
- UI / API / Assistant / CLI 复用同一 catalog（单一来源，避免多处硬编码文案）。

本模块只依赖标准库：不 import 任何领域模块、不含阈值、不产生事实。
"""

from __future__ import annotations

from dataclasses import dataclass

